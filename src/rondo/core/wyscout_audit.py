"""A hand-check sheet for the Wyscout coordinate conversion (``make report``).

Samples a few actions whose true position is known from the laws of the game, shows the raw
Wyscout position (0-100, each team attacking left to right, y from the top) next to the SPADL
position (metres, 105 x 68, each team attacking left to right, y from the bottom), and says
where each should be. A few are checked by hand.
"""

from __future__ import annotations

from pathlib import Path

from rondo.core import store

SAMPLES = [
    (
        "Corner, left flag of the attacked goal",
        "e.subtype_name = 'Corner' and e.y <= 5",
        "SPADL near (105, 68)",
    ),
    (
        "Corner, right flag of the attacked goal",
        "e.subtype_name = 'Corner' and e.y >= 95",
        "SPADL near (105, 0)",
    ),
    (
        "Penalty (in play)",
        "e.subtype_name = 'Penalty' and e.period < 5 and e.x >= 50",
        "SPADL near (94, 34): 11 m from the goal line, centred",
    ),
    (
        "Goal kick",
        "e.subtype_name = 'Goal kick'",
        "SPADL (5, 34): socceraction places every goal kick there",
    ),
    (
        "Kick-off pass (raw (50, 50))",
        "e.type_name = 'Pass' and e.x = 50 and e.y = 50 and e.event_sec < 5",
        "SPADL (52.5, 34): the centre spot",
    ),
]


def render(parquet: Path, per_kind: int = 3) -> str:
    """Render ``reports/wyscout_coordinate_audit.md``."""
    con = store.connect()
    store.create_views(con, parquet)
    lines = [
        "# Wyscout coordinate audit (hand check)",
        "",
        "Generated by `make report`. Don't edit by hand. Each row is one Wyscout event and the "
        "SPADL action it became, sampled deterministically (smallest event ids). Raw positions "
        "are Wyscout's 0-100 scale with y from the top; SPADL is 105 x 68 m with y from the "
        "bottom, so SPADL x = raw x * 1.05 and SPADL y = (100 - raw y) * 0.68, apart from the "
        "documented goal-kick placement.",
        "",
        "| Kind | Event id | Match | Raw (x, y) | SPADL (x, y) | Where it should be |",
        "|---|---|---|---|---|---|",
    ]
    for kind, cond, expect in SAMPLES:
        rows = con.execute(
            f"""select e.event_id, e.match_id, e.x, e.y, a.start_x, a.start_y
                from wy_events e join spadl_actions a on a.provider = 'wyscout'
                 and a.original_event_id = cast(e.event_id as varchar)
                where {cond} order by e.event_id limit {per_kind}"""
        ).fetchall()
        for eid, mid, x, y, sx, sy in rows:
            lines.append(
                f"| {kind} | {eid} | {mid} | ({x:g}, {y:g}) | ({sx:.2f}, {sy:.2f}) | {expect} |"
            )
    con.close()
    return "\n".join(lines) + "\n"
