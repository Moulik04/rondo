"""``make report``: generated reports for the shared data and GPU runs.

- ``reports/statsbomb_summary.md``: per competition-season counts (matches, events, players,
  minutes, shots, non-penalty shots with freeze frames, 360 frames, SPADL actions);
- ``reports/gpu_ledger.md``: every GPU run copied back under ``data/runs/``, against the budget
  in ``jobs/core/budget.yaml``.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

from rondo.core import runs, store
from rondo.core.paths import (
    REPO_ROOT,
    data_dir,
    duckdb_path,
    parquet_dir,
    reports_dir,
    statsbomb_raw_dir,
)

SUMMARY_SQL = """
with m as (select competition_id, season_id, count(*) as matches,
                  sum(has_360::int) as matches_360 from matches group by all),
e as (select competition_id, season_id, count(*) as events from events group by all),
p as (select competition_id, season_id, count(distinct player_id) as players,
             sum(minutes) as minutes from player_match_minutes group by all),
s as (select competition_id, season_id, count(*) as shots,
             sum((not is_penalty)::int) as np_shots,
             sum((not is_penalty and has_freeze_frame)::int) as np_with_ff
      from shots group by all),
f as (select competition_id, season_id, count(*) as frames_360 from visible_areas_360
      group by all),
a as (select competition_id, season_id, count(*) as spadl from spadl_actions
      where provider = 'statsbomb' group by all)
select c.competition_name, c.season_name, c.scope, c.scope_group, m.matches, m.matches_360,
       e.events, p.players, p.minutes, s.shots, s.np_shots, s.np_with_ff,
       coalesce(f.frames_360, 0), a.spadl
from competitions c
join m using (competition_id, season_id)
join e using (competition_id, season_id)
join p using (competition_id, season_id)
join s using (competition_id, season_id)
left join f using (competition_id, season_id)
join a using (competition_id, season_id)
order by c.scope, c.competition_name, c.season_name
"""

HEADER = (
    "| Competition | Season | Scope | Group | Matches | With 360 | Events | Players who played | "
    "Minutes | Shots | Non-pen. shots | …with freeze frame | 360 frames | SPADL actions |"
)


def _fmt(v: object) -> str:
    if isinstance(v, float):
        return f"{v:,.0f}"
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def statsbomb_summary(parquet: Path) -> str:
    """Render the per competition-season summary from the shared tables."""
    con = store.connect()
    store.create_views(con, parquet)
    rows = con.execute(SUMMARY_SQL).fetchall()
    totals = con.execute(
        """select (select count(*) from matches), (select sum(has_360::int) from matches),
                  (select count(*) from events),
                  (select count(distinct player_id) from player_match_minutes),
                  (select sum(minutes) from player_match_minutes),
                  (select count(*) from shots), (select sum((not is_penalty)::int) from shots),
                  (select sum((not is_penalty and has_freeze_frame)::int) from shots),
                  (select count(*) from visible_areas_360),
                  (select count(*) from spadl_actions where provider = 'statsbomb')"""
    ).fetchall()[0]
    con.close()
    lines = [
        "# StatsBomb data summary",
        "",
        "Generated by `make report` from `data/parquet/`. Don't edit by hand. "
        "Minutes are elapsed playing minutes (see `docs/DATA_CONTRACT.md`); "
        "360 frames count events that have a 360 frame.",
        "",
        HEADER,
        "|" + "---|" * 14,
    ]
    lines += ["| " + " | ".join(_fmt(v) for v in r) + " |" for r in rows]
    lines.append("| **Total** | | | | " + " | ".join(f"**{_fmt(v)}**" for v in totals) + " |")
    return "\n".join(lines) + "\n"


def _du(path: Path) -> int:
    """Bytes on disk under ``path`` (files only)."""
    return sum(f.stat().st_size for f in path.rglob("*") if f.is_file()) if path.exists() else 0


def performance(log: Path, raw: Path, parquet: Path, db: Path) -> str:
    """Render the performance note from the ``make data`` log and measured sizes."""
    text = log.read_text() if log.exists() else ""
    real = re.search(r"([\d.]+) real", text)
    user = re.search(r"([\d.]+) user", text)
    total = re.search(r"^\[duckdb\].*total (\d+)s", text, re.M)
    rss = re.search(r"(\d+)\s+maximum resident set size", text)
    steps = re.findall(r"^\[(\w+)\].*?(\d+)s", text, re.M)
    gb = 1e9
    lines = [
        "# Performance: `make data`",
        "",
        "Generated by `make report` from `data/logs/make_data.log` (macOS `/usr/bin/time -l`) "
        "and file sizes on disk. Don't edit by hand.",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Build time (the build's own clock, which pauses while the Mac sleeps) | "
        f"{int(total.group(1)) / 60:.1f} min |"
        if total
        else "| Build time | unmeasured |",
        f"| CPU time (user) | {float(user.group(1)) / 60:.1f} min |"
        if user
        else "| CPU time (user) | unmeasured |",
        f"| Elapsed wall clock (`/usr/bin/time`; includes any time the Mac slept) | "
        f"{float(real.group(1)) / 60:.1f} min |"
        if real
        else "| Elapsed wall clock | unmeasured |",
        f"| Peak memory (max resident set) | {int(rss.group(1)) / gb:.2f} GB |"
        if rss
        else "| Peak memory (max resident set) | unmeasured |",
    ]
    # The [duckdb] line reports the build's total, not a step time of its own.
    lines += [f"| Step: {name} | {secs} s |" for name, secs in steps if name != "duckdb"]
    fetch_log = log.parent / "statsbomb_fetch.log"
    f_text = fetch_log.read_text() if fetch_log.exists() else ""
    f_real = re.search(r"([\d.]+) real", f_text)
    f_rss = re.search(r"(\d+)\s+maximum resident set size", f_text)
    if f_real and f_rss:
        lines.append(
            f"| First fetch (download and checksums) | {float(f_real.group(1)) / 60:.1f} min, "
            f"peak {int(f_rss.group(1)) / gb:.2f} GB |"
        )
    lines += [
        f"| Raw StatsBomb checkout (JSON files) | {_du(raw / 'open-data' / 'data') / gb:.2f} GB |",
        f"| Raw git objects (partial clone) | {_du(raw / 'open-data' / '.git') / gb:.2f} GB |",
        f"| Raw Wyscout (zips and extracted JSON) | {_du(raw.parent / 'wyscout') / gb:.2f} GB |",
        f"| Raw DFL (XML) | {_du(raw.parent / 'dfl') / gb:.2f} GB |",
        f"| Parquet (`data/parquet/`) | {_du(parquet) / gb:.2f} GB |",
        f"| DuckDB file (views only) | {db.stat().st_size / 1e6:.1f} MB |"
        if db.exists()
        else "| DuckDB file | not built |",
    ]
    lines += [
        "",
        "`make data` reuses the pinned checkout when it already matches `SOURCE.json`, so its "
        "fetch step takes no time; the first fetch is timed in its own log.",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write every report this phase can generate."""
    out = reports_dir()
    out.mkdir(exist_ok=True)
    pq = parquet_dir()
    if (pq / "matches.parquet").exists():
        (out / "statsbomb_summary.md").write_text(statsbomb_summary(pq))
        print(f"wrote {out / 'statsbomb_summary.md'}")
        (out / "performance.md").write_text(
            performance(
                data_dir() / "logs" / "make_data.log", statsbomb_raw_dir(), pq, duckdb_path()
            )
        )
        print(f"wrote {out / 'performance.md'}")
    else:
        print("no data/parquet yet (run make data); skipping statsbomb_summary.md")
    if (pq / "match_xref.parquet").exists():
        from rondo.core.provider_comparison import render

        (out / "provider_comparison.md").write_text(render(pq))
        print(f"wrote {out / 'provider_comparison.md'}")
    if (pq / "wy_events").exists() and (pq / "tracking_meta.parquet").exists():
        from rondo.core.sources_summary import render as render_sources

        (out / "sources_summary.md").write_text(render_sources(pq))
        print(f"wrote {out / 'sources_summary.md'}")
    if (pq / "wy_events").exists():
        from rondo.core.wyscout_audit import render as render_audit

        (out / "wyscout_coordinate_audit.md").write_text(render_audit(pq))
        print(f"wrote {out / 'wyscout_coordinate_audit.md'}")
    if (pq / "player_age_status.parquet").exists():
        from rondo.core.identity_report import write_all

        for path in write_all(pq, out):
            print(f"wrote {path}")
    budget = yaml.safe_load((REPO_ROOT / "jobs" / "core" / "budget.yaml").read_text())
    all_runs = runs.load_runs(data_dir() / "runs")
    (out / "gpu_ledger.md").write_text(runs.render_ledger(all_runs, budget))
    print(f"wrote {out / 'gpu_ledger.md'} ({len(all_runs)} runs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
